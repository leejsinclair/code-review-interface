/** An alignment citation is `{ type: 'code', ... }` where a claim ref is `{ kind: 'code', ... }`. */
function asCitation(ref: ReturnType<typeof code>) {
  const { kind, ...rest } = ref;
  return { type: kind, ...rest };
}

