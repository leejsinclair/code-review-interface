const text = (...lines: string[]): string => `${lines.join('\n')}\n`;
/** The 1-based line of `file` holding `needle`, so citations follow the content. */
function lineOf(file: string, needle: string): number {
  const i = file.split('\n').findIndex((l) => l.includes(needle));
  if (i === -1) throw new Error(`demo text has no line with ${needle}`);
  return i + 1;
}

