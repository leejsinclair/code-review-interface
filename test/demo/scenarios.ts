const SESSION = text(
  "import { randomBytes, timingSafeEqual } from 'node:crypto';",
  "import type { Db } from '../db.ts';",
  '',
  'const SESSION_TTL_MS = 30 * 24 * 60 * 60 * 1000;',
  '',
  '/** Creates a session for a signed-in shopper and returns its token. */',
  'export async function createSession(db: Db, userId: string): Promise<string> {',
  "  const token = randomBytes(32).toString('base64url');",
  "  await db.insert('sessions', { token, userId, expiresAt: Date.now() + SESSION_TTL_MS });",
  '  return token;',
  '}',
  '',
  '/** The shopper a session token belongs to, or null when it is unknown or expired. */',
  'export async function userForToken(db: Db, token: string): Promise<string | null> {',
  "  const row = await db.findOne('sessions', { token });",
  '  if (row === null || row.expiresAt < Date.now()) return null;',
  '  return timingSafeEqual(Buffer.from(row.token), Buffer.from(token)) ? row.userId : null;',
  '}',
);

